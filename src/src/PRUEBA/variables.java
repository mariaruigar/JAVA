package PRUEBA;

public class variables {
	public static void main (String[] args) {
		//Definimos varaibles de tipo entero
		byte numeroMuyPequeño= 100;
		short numeroPequeño= 3550;
		//Ademas de declarar, le podemos dar un valor inicial.
		int numeroEstandar = 3550;
		long numeroGrande;
		
		//Para variables numericas decimales
		
		float decimalPequeño= 3.15F;
		double decimalGrande= 3.15;
		
		
		//Existen variables que permiten guardar caracteres
		char caracter1 = 'p';
		char caracter2 = 'j';
		char caracter3 = '3';
		char caracter4 = ':';
		char caracter5 = '/';
		
		//Hay variables logicas, se usan mucho en bucles y condicionales.
		boolean verdadero=true;
		boolean falso=false;
		
		//Aunque no sea de tipo basico metemos aqui el string
		String cadena = "Hola soy una cadena de caracteres";
				
	}
}